import { galleryItems } from "./gallery";
import { photo } from "./photos";

export type TourView = {
  title: string;
  place: string;
  elevation: string;
  mountainName: string;
  mountainElevation: string;
  description: string;
  image: string;
  imageAlt: string;
};

const scenicImages = [
  photo("manangRoad"),
  photo("manang"),
  photo("muktinath"),
  photo("mustang"),
  photo("kagbeni"),
  photo("pathivara"),
  photo("kalinchowk"),
  photo("sailung"),
  photo("halesi"),
  photo("gosaikunda"),
  photo("dhorpatan"),
  photo("charDham"),
  photo("amaYangri"),
  photo("pokhara"),
  photo("bandipur"),
  photo("annapurnaPanorama"),
  photo("boudhanath"),
  photo("kathmandu"),
  ...galleryItems.map((item) => ({ src: item.image, alt: `${item.title} at ${item.place}` })),
];

function view(
  title: string,
  place: string,
  elevation: string,
  mountainName: string,
  mountainElevation: string,
  description: string,
  imageIndex: number,
): TourView {
  const image = scenicImages[imageIndex % scenicImages.length] ?? scenicImages[0];
  if (!image) throw new Error("Tour view image pool is empty");
  return {
    title,
    place,
    elevation,
    mountainName,
    mountainElevation,
    description,
    image: image.src,
    imageAlt: image.alt,
  };
}

